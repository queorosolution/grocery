package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"strings"
)

const tsHeader = "// Code generated by cmd/gen from contracts/enums.json. DO NOT EDIT.\n\n"

func jsonString(s string) string {
	var b bytes.Buffer
	enc := json.NewEncoder(&b)
	enc.SetEscapeHTML(false)
	_ = enc.Encode(s) // a string always encodes
	return strings.TrimSpace(b.String())
}

func tsList(values []string) string {
	q := make([]string, len(values))
	for i, v := range values {
		q[i] = jsonString(v)
	}
	return strings.Join(q, ", ")
}

func emitTSEnums(c *Contract) output {
	var b strings.Builder
	b.WriteString(tsHeader)
	for _, name := range sortedKeys(c.Enums) {
		list := lowerFirst(name) + "Values"
		fmt.Fprintf(&b, "export const %s = [%s] as const;\n", list, tsList(c.Enums[name]))
		fmt.Fprintf(&b, "export type %s = (typeof %s)[number];\n", name, list)
		fmt.Fprintf(&b, "export const is%s = (v: unknown): v is %s => (%s as readonly unknown[]).includes(v);\n\n", name, name, list)
	}
	return output{Path: "src/lib/enums.gen.ts", Data: []byte(strings.TrimRight(b.String(), "\n") + "\n")}
}

// emitTSPerms is for UI hints only. The server decides what a user may do.
func emitTSPerms(c *Contract) output {
	var b strings.Builder
	b.WriteString(tsHeader + "import type { Permission, Role } from \"./enums.gen\";\n\n")
	b.WriteString("export const rolePermissions: Record<Role, readonly Permission[]> = {\n")
	for _, role := range c.Enums["Role"] {
		fmt.Fprintf(&b, "  %s: [%s],\n", role, tsList(c.RolePermissions[role]))
	}
	b.WriteString("};\n\n")
	b.WriteString("export const conditionalPermissions: Partial<Record<Role, Partial<Record<Permission, string>>>> = {\n")
	for _, role := range c.Enums["Role"] {
		conds, ok := c.ConditionalPermissions[role]
		if !ok {
			continue
		}
		fmt.Fprintf(&b, "  %s: {\n", role)
		for _, p := range c.Enums["Permission"] {
			if cond, ok := conds[p]; ok {
				fmt.Fprintf(&b, "    %s: %s,\n", jsonString(p), jsonString(cond))
			}
		}
		b.WriteString("  },\n")
	}
	b.WriteString("};\n")
	return output{Path: "src/lib/perms.gen.ts", Data: []byte(b.String())}
}

func emitTSErrors(c *Contract) output {
	var b strings.Builder
	b.WriteString(tsHeader + "export const errorCodes = {\n")
	for _, name := range sortedKeys(c.ErrorCodes) {
		e := c.ErrorCodes[name]
		fmt.Fprintf(&b, "  %s: { http: %d, message: %s },\n", name, e.HTTP, jsonString(e.Message))
	}
	b.WriteString("} as const;\n\nexport type ErrorCode = keyof typeof errorCodes;\n")
	return output{Path: "src/lib/errors.gen.ts", Data: []byte(b.String())}
}

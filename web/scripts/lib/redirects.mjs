import { readdir } from "node:fs/promises";
import path from "node:path";

// Dynamic folders that are NOT private id routes. Shop pages are built one by one, so a
// catch-all rewrite would hide them (docs/08 section 11.1).
const PREBUILT = new Set(["slug"]);

/** Route folders like "/order/[id]" for every page.tsx that has a dynamic folder in its path. */
export async function findIdRoutes(appDir) {
  const routes = [];
  async function walk(dir, parts) {
    const entries = await readdir(dir, { withFileTypes: true });
    if (entries.some((e) => e.isFile() && /^page\.(tsx|ts|jsx|js)$/.test(e.name))) {
      const dynamic = parts.filter((p) => /^\[[^\]]+\]$/.test(p));
      if (dynamic.length > 0 && !dynamic.every((p) => PREBUILT.has(p.slice(1, -1)))) routes.push(`/${parts.join("/")}`);
    }
    for (const e of entries) {
      if (!e.isDirectory() || e.name.startsWith("_") || e.name.startsWith("@")) continue;
      // (group) folders are not part of the URL.
      const isGroup = /^\(.+\)$/.test(e.name);
      await walk(path.join(dir, e.name), isGroup ? parts : [...parts, e.name]);
    }
  }
  await walk(appDir, []);
  return routes.sort();
}

/** "/order/[id]" -> { from: "/order/:id", to: "/order/_/" }. */
export function toRule(route) {
  const from = route.replace(/\[([^\]]+)\]/g, ":$1");
  const to = `${route.replace(/\[[^\]]+\]/g, "_")}/`;
  return { from, to };
}

/** The text of public/_redirects: one rewrite (status 200) with and without the trailing slash. */
export function buildRedirects(routes) {
  const seen = new Set();
  const lines = [];
  for (const route of routes) {
    const { from, to } = toRule(route);
    if (seen.has(from)) throw new Error(`two routes rewrite ${from}`);
    seen.add(from);
    lines.push(`${from}  ${to}  200`, `${from}/  ${to}  200`);
  }
  if (lines.length > 100) throw new Error(`${lines.length} rules; Cloudflare Pages allows 100`);
  return [
    "# GENERATED by scripts/gen-redirects.mjs from the route folders. Do not edit.",
    "# Private id pages are one placeholder file; these rewrites (status 200) keep the real URL.",
    ...lines,
    "",
  ].join("\n");
}

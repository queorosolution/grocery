import { buildCsp, hasInlineHandlers, hashOf, inlineScripts, pagePatterns, sampleUrl } from "./csp.mjs";
import { headersFor, parseHeaders } from "./headers.mjs";

// Cloudflare Pages limits (developers.cloudflare.com/pages/configuration/headers).
export const MAX_RULES = 100;
export const MAX_LINE = 2000;

const CSP = "Content-Security-Policy";
const NOT_BUILT = "/s/shop-newer-than-this-build/"; // where 404.html is served for a shop page

const hashesOf = (html) => [...new Set(inlineScripts(html).map(hashOf))];

/**
 * @param {string} base  contents of public/_headers (headers for every page, no CSP)
 * @param {Record<string,string>} pages  html by path inside out/, for example { "index.html": "<html>…" }
 * @param {{apiBase?:string,cartApiBase?:string,imgBase?:string}} hosts
 * @param {{from:string,to:string}[]} redirects  the rewrites of public/_redirects
 */
export function buildHeadersFile(base, pages, hosts, redirects = []) {
  const blocks = [];
  const policy = (hashes) => buildCsp({ ...hosts, hashes });
  const notFound = pages["404.html"];
  // Anything without a file of its own is served 404.html, so it gets that page's hashes.
  blocks.push(`/*\n  ${CSP}: ${policy(notFound ? hashesOf(notFound) : [])}`);
  for (const [file, html] of Object.entries(pages).sort(([a], [b]) => a.localeCompare(b))) {
    if (file === "404.html") continue;
    const own = `  ! ${CSP}\n  ${CSP}: ${policy(hashesOf(html))}`;
    for (const pattern of pagePatterns(file, redirects)) blocks.push(`${pattern}\n${own}`);
  }
  return `${base.trimEnd()}\n\n# Generated by scripts/csp-hashes.mjs. Do not edit.\n${blocks.join("\n\n")}\n`;
}

/** Everything that must hold for the built site. Returns a list of problems (empty = fine). */
export function checkSite(headersText, pages, redirects = []) {
  const problems = [];
  const rules = parseHeaders(headersText);
  if (rules.length > MAX_RULES) problems.push(`${rules.length} header rules; Cloudflare allows ${MAX_RULES}`);
  headersText.split("\n").forEach((line, i) => {
    if (line.length > MAX_LINE) problems.push(`_headers line ${i + 1} is ${line.length} characters; Cloudflare allows ${MAX_LINE}`);
  });

  for (const [file, html] of Object.entries(pages)) {
    const url = file === "404.html" ? NOT_BUILT : sampleUrl(file, redirects);
    const csp = headersFor(rules, url).get(CSP.toLowerCase());
    if (!csp) {
      problems.push(`${file}: no Content-Security-Policy for ${url}`);
      continue;
    }
    const script = /(?:^|;\s*)script-src ([^;]*)/.exec(csp)?.[1] ?? "";
    if (script.includes("'unsafe-inline'") || script.includes("'unsafe-eval'")) problems.push(`${file}: script-src allows unsafe code`);
    if (csp.includes(", default-src")) problems.push(`${file}: two policies were combined for ${url}`);
    for (const h of hashesOf(html)) if (!script.includes(h)) problems.push(`${file}: inline script ${h} is not allowed by script-src`);
    if (hasInlineHandlers(html)) problems.push(`${file}: has an inline event handler (onclick=…), which a hash cannot allow`);
  }
  return problems;
}
